export type SimdMode = "auto" | "off" | "fixed" | "relaxed";

export function detectSimd() {
  const validate = (bytes: number[]) => {
    try {
      return WebAssembly.validate(Uint8Array.from(bytes));
    } catch {
      return false;
    }
  };
  const fixed = validate([0x00,0x61,0x73,0x6d,0x01,0x00,0x00,0x00,0x01,0x05,0x01,0x60,0x00,0x01,0x7b,0x03,0x02,0x01,0x00,0x0a,0x0a,0x01,0x08,0x00,0x41,0x00,0xfd,0x0f,0xfd,0x62,0x0b]);
  const relaxed = validate([0x00,0x61,0x73,0x6d,0x01,0x00,0x00,0x00,0x01,0x05,0x01,0x60,0x00,0x01,0x7b,0x03,0x02,0x01,0x00,0x0a,0x0f,0x01,0x0d,0x00,0x41,0x01,0xfd,0x0f,0x41,0x02,0xfd,0x0f,0xfd,0x80,0x02,0x0b]);
  return { fixed, relaxed };
}

export function resolveSimd(mode: SimdMode): boolean | "fixed" | "relaxed" {
  const d = detectSimd();
  if (mode === "off") return false;
  if (mode === "relaxed") return d.relaxed ? "relaxed" : d.fixed ? "fixed" : false;
  if (mode === "fixed") return d.fixed ? "fixed" : false;
  if (d.relaxed) return "relaxed";
  if (d.fixed) return "fixed";
  return false;
}

export function fallbackSimd(current: boolean | string) {
  const d = detectSimd();
  if (current === "relaxed" && d.fixed) return "fixed" as const;
  return false as const;
}
